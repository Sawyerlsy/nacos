CREATE UNIQUE INDEX uk_tenantcapacity ON tenant_capacity(tenant_id);

/******************************************/
/*   表名称 = tenant_info   */
/******************************************/
CREATE TABLE tenant_info (
                             id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
                             kp VARCHAR(128) NOT NULL,
                             tenant_id VARCHAR(128) DEFAULT '',
                             tenant_name VARCHAR(128) DEFAULT '',
                             tenant_desc VARCHAR(256),
                             create_source VARCHAR(32),
                             gmt_create BIGINT NOT NULL,
                             gmt_modified BIGINT NOT NULL,
                             PRIMARY KEY (id)
);
CREATE UNIQUE INDEX uk_tenantinfo_kptenantid ON tenant_info(kp, tenant_id);
CREATE INDEX idx_tenantinfo_tenant_id ON tenant_info(tenant_id);

/******************************************/
/*   表名称 = users   */
/******************************************/
CREATE TABLE users (
                       username VARCHAR(50) PRIMARY KEY,
                       password VARCHAR(500) NOT NULL,
                       enabled BOOLEAN NOT NULL
);

CREATE TABLE roles (
                       username VARCHAR(50) NOT NULL,
                       role VARCHAR(50) NOT NULL
);
CREATE UNIQUE INDEX idx_user_role ON roles(username, role);

CREATE TABLE permissions (
                               role VARCHAR(50) NOT NULL,
                               resource VARCHAR(255) NOT NULL,
                               action VARCHAR(8) NOT NULL
);
CREATE UNIQUE INDEX uk_role_permission ON permissions(role,resource,action);

