/******************************************/
/*   表名称 = config_info                  */
/******************************************/
CREATE TABLE config_info (
                             id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
                             data_id VARCHAR(255) NOT NULL,
                             group_id VARCHAR(128),
                             content TEXT NOT NULL,
                             md5 VARCHAR(32),
                             gmt_create TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
                             gmt_modified TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
                             src_user TEXT,
                             src_ip VARCHAR(50),
                             app_name VARCHAR(128),
                             tenant_id VARCHAR(128) DEFAULT '',
                             c_desc VARCHAR(256),
                             c_use VARCHAR(64),
                             effect VARCHAR(64),
                             type VARCHAR(64),
                             c_schema TEXT,
                             encrypted_data_key TEXT,
                             PRIMARY KEY (id)
);
COMMENT ON TABLE config_info IS 'config_info';
CREATE UNIQUE INDEX uk_configinfo_datagrouptenant ON config_info(data_id, group_id, tenant_id);

/******************************************/
/*   表名称 = config_info_gray   */ /* 新增表 */
/******************************************/
CREATE TABLE config_info_gray (
                                  id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
                                  data_id VARCHAR(255) NOT NULL,
                                  group_id VARCHAR(128) NOT NULL,
                                  content TEXT NOT NULL,
                                  md5 VARCHAR(32),
                                  src_user TEXT,
                                  src_ip VARCHAR(100),
                                  gmt_create TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
                                  gmt_modified TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
                                  app_name VARCHAR(128),
                                  tenant_id VARCHAR(128) DEFAULT '',
                                  gray_name VARCHAR(128) NOT NULL, /* 新增字段 */
                                  gray_rule TEXT NOT NULL, /* 新增字段 */
                                  encrypted_data_key TEXT NULL, /* 新增字段 */
                                  PRIMARY KEY (id)
);
COMMENT ON TABLE config_info_gray IS 'config_info_gray';
CREATE UNIQUE INDEX uk_configinfogray_datagrouptenantgray ON config_info_gray(data_id, group_id, tenant_id, gray_name);
CREATE INDEX idx1_configinfogray ON config_info_gray(data_id, gmt_modified);
CREATE INDEX idx2_configinfogray ON config_info_gray(gmt_modified);

/******************************************/
/*   表名称 = config_tags_relation   */
/******************************************/
CREATE TABLE config_tags_relation (
                                      id BIGINT NOT NULL,
                                      tag_name VARCHAR(128) NOT NULL,
                                      tag_type VARCHAR(64),
                                      data_id VARCHAR(255) NOT NULL,
                                      group_id VARCHAR(128) NOT NULL,
                                      tenant_id VARCHAR(128) DEFAULT '',
                                      nid BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
                                      PRIMARY KEY (nid)
);
CREATE UNIQUE INDEX uk_configtagrelation_configidtag ON config_tags_relation(id, tag_name, tag_type);
CREATE INDEX idx_configtagrelation_tenant_id ON config_tags_relation(tenant_id);

/******************************************/
/*   表名称 = group_capacity   */
/******************************************/
CREATE TABLE group_capacity (
                                id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
                                group_id VARCHAR(128) NOT NULL DEFAULT '',
                                quota INT NOT NULL DEFAULT 0,
                                usage INT NOT NULL DEFAULT 0,
                                max_size INT NOT NULL DEFAULT 0,
                                max_aggr_count INT NOT NULL DEFAULT 0,
                                max_aggr_size INT NOT NULL DEFAULT 0,
                                max_history_count INT NOT NULL DEFAULT 0,
                                gmt_create TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
                                gmt_modified TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
                                PRIMARY KEY (id)
);
COMMENT ON TABLE group_capacity IS '集群、各Group容量信息表';
CREATE UNIQUE INDEX uk_groupcapacity ON group_capacity(group_id);

/******************************************/
